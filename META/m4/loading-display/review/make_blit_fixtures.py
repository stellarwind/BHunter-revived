from fractions import Fraction as F
from pathlib import Path
import struct
ROOT=Path(__file__).resolve().parents[4]
def f32(x):return struct.unpack('<f',struct.pack('<f',float(x)))[0]
def bits(x):return struct.unpack('<I',struct.pack('<f',float(x)))[0]
def trunc(x):return int(x)
out=['/* Independent rational endpoint fixtures; generated by make_blit_fixtures.py. */']
for width,height in [(8,6),(9,7),(13,11),(32,24)]:
 for kind,start,end in [(0,F(0),F(1,8)),(1,F(1,8),F(3,8)),(2,F(3,8),F(5,8)),(3,F(5,8),F(7,8)),(4,F(7,8),F(1))]:
  for a,b in [(start,end),((start+end)/2,end),((start+end)/2,(start+end)/2),(start-F(1,4),end+F(1,4)),(end,start)]:
   scale=8 if kind in (0,4) else 4
   aa=F.from_float(f32((f32(a)-float(start))*scale));bb=F.from_float(f32((f32(b)-float(start))*scale))
   w,h=width//2,height//2;rows=[0]*height
   if kind in (0,2,4):
    for dy in range(h):
     ray=F((h-dy)*w,h)
     if kind==0:lo,hi=trunc(w+ray*aa),trunc(w+ray*bb);y=dy
     elif kind==2:
      lo=trunc(w+F(dy*w,h)*(1-2*bb));hi=trunc(w+F(dy*w,h)*(1-2*aa)+1);y=h+dy
     else:lo,hi=trunc(w-ray*(1-aa)),trunc(w-ray*(1-bb));y=dy
     for x in range(max(0,lo),min(width,hi)):rows[y]|=1<<x
   else:
    for dx in range(w):
     ray=F(dx*h,w)
     if kind==1:lo,hi=trunc(h+ray*(2*aa-1)),trunc(h+ray*(2*bb-1)+1);x=w+dx
     else:lo,hi=trunc(h+ray*(1-2*bb)),trunc(h+ray*(1-2*aa)+1);x=w-dx-1
     for y in range(max(0,lo),min(height,hi)):rows[y]|=1<<x
   out.append('{%d,%d,%d,0x%08xUL,0x%08xUL,{%s}},'%(kind,width,height,bits(a),bits(b),','.join('0x%08xUL'%r for r in rows)))
(ROOT/'tests/loading_blit_cases.h').write_text('\n'.join(out)+'\n',newline='\n')
print('Created100 independent rational geometry fixtures')
