"""PC53 static golden coordinates from 00456d30's explicit x87 stores.

No restored source or original game code is executed. Python float is binary64;
f32 is used only at recovered memory stores. Angle zero avoids transcendental
implementation differences. Geometry store anchors00457215/37/65/79 and004572a8/c5/e2.
Full image UV is tested analytically; no arbitrary-UV sum fixtures apply.
"""
import math,struct,json,random
from pathlib import Path
root=Path(__file__).resolve().parents[4]
def f32(x):return struct.unpack('<f',struct.pack('<f',x))[0]
def bits(x):return struct.unpack('<I',struct.pack('<f',x))[0]
def norm(v):
 length=math.sqrt((v[0]*v[0]+v[1]*v[1])+v[2]*v[2])
 return [f32(x*(1.0/length)) for x in v] if length else v[:]
def basis(normal,up,w,h):
 n=norm([-x for x in normal]);t=norm(up)
 dot=(t[0]*n[0]+t[1]*n[1])+t[2]*n[2]
 t=norm([f32(t[i]-dot*n[i]) for i in range(3)])
 r=[f32(n[1]*t[2]-t[1]*n[2]),f32(n[2]*t[0]-t[2]*n[0]),f32(t[1]*n[0]-n[1]*t[0])]
 return [f32((x*w)*.5) for x in r],[f32((x*h)*.5) for x in t]
def corners(o,r,t):
 return [[f32((f32(o[i]-r[i]) if i<2 else o[i]-r[i])+t[i]) for i in range(3)],
         [f32((o[i]-r[i])-t[i]) for i in range(3)],
         [f32((r[i]+o[i])-t[i]) for i in range(3)],
         [f32(f32(r[i]+o[i])+t[i]) for i in range(3)]]
normal=[f32(x) for x in (-1,-2,-3)];up=[f32(x) for x in (3,-2,1)]
w=f32(173827.875);h=f32(98341.3125);r,t=basis(normal,up,w,h)
# Fixed cancellation-sensitive positive/negative origins, selected by searching
# f32 neighborhoods; every expected result still derives from instruction stores.
cases=[];coverage=[[False]*3 for _ in range(4)];rng=random.Random(0x456d30)
for attempt in range(200000):
 origin=[f32(rng.uniform(-1,1)*2**rng.randrange(-4,24)) for _ in range(3)]
 expected=corners(origin,r,t)
 naive=[[f32(((origin[i]-r[i]) if i<2 else f32(origin[i]-r[i]))+t[i]) for i in range(3)],
        [f32(f32(origin[i]-r[i])-t[i]) for i in range(3)],
        [f32(f32(origin[i]+r[i])-t[i]) for i in range(3)],
        [f32((origin[i]+r[i])+t[i]) for i in range(3)]]
 detects=[[bits(a)!=bits(b) for a,b in zip(x,y)] for x,y in zip(expected,naive)]
 if any(detects[v][i] and not coverage[v][i] for v in range(4) for i in range(3)):
  cases.append(dict(origin=origin,expected=expected,detects=detects))
  coverage=[[coverage[v][i] or detects[v][i] for i in range(3)] for v in range(4)]
 if all(all(row) for row in coverage):break
assert all(all(row) for row in coverage),coverage

def words(values):return '{'+','.join('0x%08xUL'%bits(v) for v in values)+'}'
lines=['/* Generated by META/m4/hud-attachment/plane-quad/generate_cases.py; original-instruction PC53 oracle. */',
 '#ifndef BH_PLANE_QUAD_CASES_H','#define BH_PLANE_QUAD_CASES_H',
 'typedef struct BHPlaneQuadGeometryCase {unsigned long center[3],expected[4][3];} BHPlaneQuadGeometryCase;',
 'static const unsigned long bh_plane_case_normal[3]='+words(normal)+';',
 'static const unsigned long bh_plane_case_up[3]='+words(up)+';',
 'static const unsigned long bh_plane_case_size[2]='+words([w,h])+';',
 'static const BHPlaneQuadGeometryCase bh_plane_geometry_cases[]={']
for c in cases:lines.append('{'+words(c['origin'])+',{'+','.join(words(p) for p in c['expected'])+'}},')
lines+=['};','#endif','']
(root/'tests/plane_quad_cases.h').write_text('\n'.join(lines))
(Path(__file__).resolve().parent/'golden-case-evidence.json').write_text(json.dumps(dict(normal=normal,up=up,width=w,height=h,right=r,tangent=t,geometry=cases),indent=2)+'\n')
print('generated',len(cases),'geometry cases; asymmetry detection',[[any(c['detects'][v][i] for c in cases) for i in range(3)] for v in range(4)])
