 if screen:
  #0041859d..63c: screen_radius FILD/FST; radial FST feeds X only.
  radial=radius*64*.0025
  values=[f(100+f(radial)*math.sin(midangle)),f(120-radial*math.cos(midangle)),5.0,f(length*64*.0025),angle,alpha]
