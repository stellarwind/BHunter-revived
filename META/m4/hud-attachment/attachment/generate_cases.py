import json,math,random,struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[4];HERE=Path(__file__).resolve().parent
def f(x):return struct.unpack('<f',struct.pack('<f',x))[0]
def word(x):return struct.unpack('<I',struct.pack('<f',x))[0]
def endpoint(x,z,px,pz,naive=False):
 #0041817b..1a7 and004182a0..2de: retain delta once, reload FST for one factor.
 rx=x-px;rz=z-pz;sx=f(rx);sz=f(rz)
 return [sx,sz,f(math.sqrt((sx*sx+sz*sz) if naive else (rx*sx+rz*sz)))]
def project(a,b,px,pz,yaw,screen,naive_clip=False,naive_endpoint=False,naive_mid=False):
 a=endpoint(*a,px,pz,naive_endpoint);b=endpoint(*b,px,pz,naive_endpoint)
 before=[a[:],b[:]]
 if a[2]<400 and b[2]>400:
  #00418332..39 difference FST;00418352/60 store weights but retain originals.
  denominator=f(b[2]-a[2]);ra=(b[2]-400)/denominator;rb=(400-a[2])/denominator
  fa=f(ra);fb=f(rb)
  b=[f((fa if naive_clip else ra)*a[0]+(fb if naive_clip else rb)*b[0]),f(fa*a[1]+fb*b[1]),400]
 elif a[2]>=400 and b[2]<400:
  #004183e3..45e: symmetric first-endpoint update, same mixed weights.
  denominator=f(a[2]-b[2]);ra=(400-b[2])/denominator;rb=(a[2]-400)/denominator
  fa=f(ra);fb=f(rb)
  a=[f((fa if naive_clip else ra)*a[0]+(fb if naive_clip else rb)*b[0]),f(fa*a[1]+fb*b[1]),400]
 elif a[2]>=400:return None
 #004184c5..574: midpoint X retained and stored; midpoint Z retained for square.
 mx=(a[0]+b[0])*.5;mz=(a[1]+b[1])*.5
