 px=f(rng.choice([0,4096,-8192])+rng.uniform(-2,2));pz=f(rng.choice([0,2048,-4096])+rng.uniform(-2,2))
 a=(f(px+rng.uniform(-600,600)),f(pz+rng.uniform(-600,600)))
 b=(f(px+rng.uniform(-300,300)),f(pz+rng.uniform(-300,300)))
 yaw=f(rng.uniform(-3,3));screen=bool(rng.randrange(2))
