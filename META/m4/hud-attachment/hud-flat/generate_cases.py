"""Narrow static x87 store probes for odd signed viewport widths.
No source/game code is executed. Probe formulas name the pinned instruction
sites that retain raw half dimensions versus reload cached float dimensions.
"""
import json,struct,random
from pathlib import Path
ROOT=Path(__file__).resolve().parents[4];HERE=Path(__file__).resolve().parent
def f(x):return struct.unpack('<f',struct.pack('<f',x))[0]
def bits(x):return struct.unpack('<I',struct.pack('<f',x))[0]
found={}
for width in range(1,10000):
 height=479;raw_scale=width*.0015625;s=f(raw_scale)
 h=f(s*18);w=f(s*12);bottom=f(s*25);offset=f(s*60)
 ih=f(s*38);iw=f(s*96);top=f(height-s*34);lh=f(s*14)
 probes=[
 # index relative to first queued record:2 primary hundreds,4 primary units,
 #5 primary icon,10 counter labelA,11 first counter digit,18 counter labelB.
 ('raw_first_bar_height',0,3,f(raw_scale*150),f(s*150),'0041a3fa..1a41a'),
 ('primary_hundred_x',2,0,f(s*112-s*60+(s*12)*.5),f(s*112-offset+w*.5),'0041a80d/1a829/1a8a8'),
 ('primary_hundred_y',2,1,f(height-s*25+(s*18)*.5),f(height-bottom+h*.5),'0041a7f7/1a82f/1a853'),
 ('primary_unit_x',4,0,f(s*136-offset+(s*12)*.5),f(s*136-offset+w*.5),'0041aa66/1aa95'),
 ('primary_unit_y',4,1,f(height-bottom+(s*18)*.5),f(height-bottom+h*.5),'0041aa2d/1aa41'),
 ('primary_icon_x',5,0,f(s*148-offset+(s*96)*.5),f(s*148-offset+iw*.5),'0041ab03/1ab11/1ab93'),
 ('primary_icon_y',5,1,f(height-ih+(s*38)*.5),f(height-ih+ih*.5),'0041aafd/1ab09/1ab7c'),
 ('counter_label_a_y',10,1,f(height-s*34+(s*14)*.5),f(top+lh*.5),'0041aef9/1af06/1af30'),
 ('counter_digit_a_y',11,1,f(top+s+(s*12)*.5),f(top+s+w*.5),'0041b020/1b024/1b049'),
 ('counter_label_b_y',18,1,f(top-s*-15+(s*14)*.5),f(top-s*-15+lh*.5),'0041b0dc/1b10e'),
 ]
 for name,index,word,expected,naive,anchor in probes:
  if name not in found and bits(expected)!=bits(naive):found[name]=dict(name=name,width=width,height=height,index=9+index,word=word,expected=bits(expected),incorrect=bits(naive),anchor=anchor)
 if len(found)==len(probes):break
assert len(found)>=6,found.keys()
cases=list(found.values())
for p in cases:p['gauge_a']=bits(-1)
rng=random.Random(0x41a3d0)
for _ in range(100000):
 width=rng.choice([639,640,641,1921,2561]);height=479;s=f(width*.0015625)
 amount=f(rng.random()*.8);rem=1-amount
 expected=f(((s*rem)*150)*.5+(450-rem*150)*s)
 naive=f(((s*rem)*150)*.5+(450-f(rem)*150)*s)
 if bits(expected)!=bits(naive):
  cases.append(dict(name='fill_retained_remainder',width=width,height=height,index=10,word=1,expected=bits(expected),incorrect=bits(naive),anchor='0041a518/1a549/1a557/1a57d',gauge_a=bits(amount)));break
else:raise AssertionError('no retained remainder sensitivity')
(HERE/'static-cases.json').write_text(json.dumps(dict(oracle='static PC53 x87 retained/store arithmetic; no original execution',cases=cases),indent=2)+'\n')
lines=['/* Static instruction-derived probes; generated by hud-flat/generate_cases.py. */',
 'typedef struct HudFlatProbe {const char *name;long width,height;unsigned long index,word,expected,gauge_a;} HudFlatProbe;',
 'static const HudFlatProbe hud_flat_probes[]={']
for p in cases:lines.append('{"%(name)s",%(width)d,%(height)d,%(index)d,%(word)d,0x%(expected)08xUL,0x%(gauge_a)08xUL},'%p)
lines.append('};');(ROOT/'tests/hud_flat_cases.h').write_text('\n'.join(lines)+'\n')
print(json.dumps(dict(probes=len(cases),original_code_executed=False)))
