"""Extract existing startup portal observations as data; never launch the game."""
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    source = ROOT / 'META/m3/startup/2e901f78ca70.json'
    data = source.read_bytes()
    record = json.loads(data)
    events = record.get('events') or [json.loads(line) for command in record['commands']
                                    if command['label'] == 'startup'
                                    for line in command['output'].splitlines() if line.startswith('{')]
    nodes = sorted((e for e in events if e['event'] == 'navigation-node'), key=lambda n: n['index'])
    ports = sorted((e for e in events if e['event'] == 'navigation-port'), key=lambda p: (p['node'], p['slot']))
    assert len(nodes) == 1454 and len(ports) == 3739
    assert record['passed'] and not record['through_first_frame'] and not record['input_injection_used']
    # Verify that fixture ordering cannot select a different match: each
    # aperture has at most one admissible opposite aperture in this snapshot.
    groups = {}
    for p in ports:
        w = p['raw_words']
        groups.setdefault((w[0], w[1]), []).append(p)
    def floats(words):
        return struct.unpack('<4f', struct.pack('<4I', *words))
    for p in ports:
        w = p['raw_words']
        a = floats(w[2:6])
        matches = []
        for q in groups.get((w[0] ^ 4, w[1]), []):
            b = floats(q['raw_words'][2:6])
            if q['node'] != p['node'] and b[0] < a[1] - .1 and a[0] + .1 < b[1] and b[2] < a[3] - .1 and a[2] + .1 < b[3]:
                matches.append(q)
        assert len(matches) == bool(p['neighbor']), (p, matches)
        if matches:
            assert matches[0]['node'] == p['neighbor_index']
    lines = ['/* Captured original startup results; generated by tools/portal_fixture.py. */',
             'static const unsigned long portal_counts[1454] = {',
             ','.join(str(n['ports']) for n in nodes), '};',
             '/* node, slot, original words 0..13, neighbor index (FFFFFFFF=none) */',
             'static const unsigned long portal_cases[3739][17] = {']
    for p in ports:
        words = [p['node'], p['slot'], *p['raw_words'][:14], p['neighbor_index']]
        lines.append('{' + ','.join('0x%xUL' % x for x in words) + '},')
    lines.append('};')
    output = ('\n'.join(lines) + '\n').encode()
    target = ROOT / 'tests/portal_cases.h'
    target.write_bytes(output)
    report = dict(source=str(source.relative_to(ROOT)), source_sha256=sha(data),
                  fixture=str(target.relative_to(ROOT)), fixture_sha256=sha(output),
                  nodes=len(nodes), portals=len(ports), connected=sum(bool(p['neighbor']) for p in ports),
                  unique_candidate_check=True, game_launches=0,
                  limitations=['Node order is snapshot index order, not a captured scene ring; uniqueness proves order independence only for this fixture.',
                               'Construction inputs use captured apertures and reconstructed initial overlap/scratch; model/geometry construction is not tested.'])
    folder = ROOT / 'META/m4/portals'
    folder.mkdir(parents=True, exist_ok=True)
    (folder / 'fixture.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report))


if __name__ == '__main__':
    main()
